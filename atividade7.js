//7. Escreva um programa que verifique se um número fornecido pelo usuário é positivo, negativo ou zero.
// Definindo a variável com o número a ser testado
var numero = 25; 

// Verificando a condição do número
if (numero > 0) {
    console.log("O número é positivo.");
} else if (numero < 0) {
    console.log("O número é negativo.");
} else {
    console.log("O número é zero.");
}